// §113.2(실기 신고 9 · 사용자 결정 2026-10-23 — 원문 *"사진 보내기는 사용자 핸드폰 내 이미지를 보낼 수 있도록"*) — 사진 보내기 턴의 서버 표기.
//
// 판정표:
// | 항목 | 정책 |
// |---|---|
// | 이미지 | 기기 화면 메모리(objectURL)에만 — 서버 업로드 · Storage · Firestore · 로그 0. 훈련이 끝나면(대화방을 떠나면) revoke |
// | 서버 · 리포트 | 사실만 — 사용자 메시지 `textMasked = PHOTO_TURN_TEXT` + `photo: true` |
// | 사기범 AI | 같은 문장을 참가자 데이터로 본다(사진 내용은 모른다) |
// | 속은 순간 | 앞선 사기범 대사가 신분증 · 사진을 요구한 뒤의 사진 턴 = 속음(`report/analyzeConversation.ts` H3) |
// ⛔ 안내 메시지(실제 사진은 저장하지 않습니다 등)를 대화방에 넣지 않는다(사용자 결정).

/** 사진 턴의 대화 표기(사기범 AI · 리포트 · 되짚어보기가 같은 문장을 쓴다). */
export const PHOTO_TURN_TEXT = "(사진 1장을 보냈다)";

/** 사기범이 사진 · 신분증을 요구한 대사인가(리포트 H3의 "요구 뒤" 판정). */
export const PHOTO_DEMAND = /신분증|사진|찍어\s*(?:서|줘|주|보내)|촬영/;

// §120(실기 신고 2026-10-23 — 사진을 보내자 1차 Claude가 *"[훈련 시뮬레이션 — 실제 신분증 사진은 받지 않습니다. 이 훈련은 여기서
// 종료됩니다.]"* 를 사기범 대사로 냈다). 사진 턴에는 사실 문장만 있고 어떻게 반응할지 지시가 없어, 모델이 '실제 신분증을 받는 상황'으로
// 읽고 캐릭터를 벗어났다(추정 — 라이브 로그상 그 턴은 claude-primary가 답했고 서버 종료는 없었다). 사진 턴에만 아래 1줄을 싣는다.
// | 사진 턴 | 지시 |
// |---|---|
// | 예(`photo: true`) | `PHOTO_TURN_INSTRUCTION` — 받은 척 짧게 반응 → 사진을 요구한 목적대로 다음 수법(훈련 · 시뮬레이션 언급 · 대괄호 고지 · 마무리 금지) |
// | 아니요 | 없음(종전 문면 바이트 동일) |
// 쓸 수 없는 응답 쪽 차단은 `llm/replyUsability.ts` `training-meta` 행이 맡는다(지시가 먹지 않아도 화면에 나가지 않게).

/** 사진 턴 지시(§120) — 캐릭터 유지형. 사진 내용은 지어내지 않는다(서버에 이미지가 없다). */
export const PHOTO_TURN_INSTRUCTION =
  "[사진 수신] 참가자가 방금 대화방으로 사진 1장을 보냈다(사진 내용은 너에게 전달되지 않는다). 캐릭터 그대로 사진을 받은 사람처럼 짧게 반응한다(예: \"고마워, 잘 받았어\"). 네가 앞서 사진 · 신분증을 요구했다면 그 목적대로 다음 단계(보증금 · 송금 · 인증번호 등 시나리오의 다음 수법)로 이어 가고, 요구한 적이 없으면 받았다고만 말한 뒤 하던 이야기를 이어 간다. 사진 속 내용을 지어내 묘사하지 않는다. 훈련 · 시뮬레이션 · 연습을 언급하거나 대괄호 안내문을 쓰거나 대화를 스스로 마무리하지 않는다.";

/** 사진 턴이면 지시 1줄, 아니면 없음. */
export function photoTurnInstruction(isPhotoTurn: boolean): string | undefined {
  return isPhotoTurn ? PHOTO_TURN_INSTRUCTION : undefined;
}

// 테스트로 고정한다(promptAssembly.test.ts "옵션 미전달 출력과 완전히 동일").
//
// ⚠️ **AC-065 하드 제약**: 이 블록들은 **압박 강도·요구 도달 속도·수법의 은밀함만** 바꾼다.
// 무해화 경계(SCENARIO_PROGRESSION의 "페이로드는 가상값만" — 실존 기관의 실제 계좌·실제 동작하는
// 앱/링크·실제 연락처 금지, AC-005/013/032/033)와 guardrailPreamble은 **세 난이도에서 완전히
// 동일**하다. "고급 = 더 진짜 같은 압박"이지 "고급 = 더 진짜에 가까운 위험 정보"가 아니다.
// 이 규칙을 문구가 아니라 **조립 순서**로 강제하는 것이 아래 buildSystemPrompt다(§15.5).
const DIFFICULTY_MODIFIERS: Record<DifficultyLevel, string | null> = {
  beginner: `[난이도 — 초급: 수법이 눈에 띄게 드러나게]
- **수법을 눈에 띄게 쓴다.** 전형적인 사기 문구를 그대로 쓰고, 요구를 서두르며, 근거는 어설프게 댄다 — 참가자가 "이건 사기구나"를 스스로 알아챌 단서를 일부러 남긴다.
- **압박은 약하게 한다.** 몰아붙이거나 겁을 주는 표현의 강도를 낮추고, 상대가 불안해하면 한 발 물러선다.
- **상대가 의심하거나 확인하려 하면 쉽게 물러선다.** 끈질기게 되받아치지 않는다.
- ⚠️ 이 난이도 지시는 **말투·압박 강도·수법의 노출 정도만** 바꾼다. 위 [진행 강제]의 "반드시 구체적인 요구에 도달한다"와 "페이로드는 가상값만", 아래 안전 지침은 **하나도 바꾸지 않는다.**`,
  // 기준선 — 블록을 내보내지 않는다(현행 프롬프트가 곧 중급, §15.3.1).
  intermediate: null,
  advanced: `[난이도 — 고급: 실제처럼 정교하게]
- **압박 강도를 높이고 요구에 더 빨리 도달한다.** 시간·권위·불이익을 근거로 결정을 재촉한다.
- **수법을 은밀히 섞는다.** 전형적인 사기 문구를 그대로 읊지 말고, 자연스러운 상담·안내 대화 안에 녹여 말한다.
- **상대가 의심해도 침착하게 해명한다.** 당황하거나 물러서지 말고 되묻고, 절차를 설명하고, 다른 근거를 대며 대화를 이어간다.
- ⚠️ **"고급"은 더 진짜 같은 압박이지, 더 진짜에 가까운 위험 정보가 아니다.** 위 [진행 강제]의 "페이로드는 가상값만"(실존 기관의 실제 계좌·실제 동작하는 앱/링크·실제 연락처 금지)과 아래 안전 지침은 고급에서도 **완전히 동일하게** 지킨다. 실제로 쓸 수 있는 사기 절차·정보를 더 알려주는 방향으로는 절대 강화하지 않는다.`,
};

/**
 * buildSystemPrompt 확장 옵션(T72, §15.5) — **호출부가 반환값 뒤에 문자열을 이어 붙이는 것을
 * 대체한다.** 추가 블록은 전부 이 옵션으로 넘겨야 guardrailPreamble 앞에 삽입된다.
 */
export type BuildSystemPromptOptions = {
  /** UX-029에서 사용자가 고른 강도. 부재·intermediate면 블록을 내보내지 않는다(기준선). */
  difficultyLevel?: DifficultyLevel;
  /**
   * T68(§15.1.4/§15.6 G1) — 이 시나리오에 통화 중 문자 카탈로그가 있는가
   * (`scenarios/inCallSms.ts` `hasInCallSms`). true면 [진행 강제]의 "화면에 없는 것을 가리키지
   * 않는다" 항목이 조건형으로 대체돼 **인증번호·계좌·링크를 요구해도 되는** 문구로 바뀐다.
   * false(기본)면 문자열이 도입 전과 완전히 동일하다(회귀 0).
   */
  inCallSmsEnabled?: boolean;
  /**
   * T83(§16.1.4) — 이 세션에서 확인 시도 무력화가 성립하는가(카탈로그 보유 **&& 고급**).
   * true면 앱 오케스트레이션과의 동기화 블록이 삽입된다(게이트 이전에 창구를 먼저 부르지 않게).
   * false(기본)면 문자열이 도입 전과 완전히 동일하다(회귀 0).
   */
  verifyInterceptEnabled?: boolean;
  /** 이 턴에만 붙는 지시(오프닝 첫 마디 지침·문자 도착 announce 지시 등). 가드레일 **앞**에 삽입된다. */
  turnInstruction?: string;
};

/**
 * 시스템 프롬프트 조립(ADR-0004 구조: personaPrompt + weakenedTactics + 대화 방식 + guardrailPreamble).
 * `scenarioPrompts/{scenarioId}` 원문은 클라가 절대 읽을 수 없고(firestore.rules), 이 조립도
 * Cloud Functions 안에서만 실행된다 — 클라이언트는 조립된 문자열을 보거나 전송받지 않는다(AC-024).
 *
 * ⚠️ **조립 순서 불변식(Architecture.md §15.5, AC-065/D-42) — 깨면 안전 설계가 코드 레벨에서 무너진다**:
 * 반환 문자열의 **마지막 블록은 언제나 `guardrailPreamble`**이다. 안전 지침이 뒤에 올수록 모델이
 * 앞선 지침보다 우선해 따르는 경향이 있어 기존 조립도 가드레일을 맨 뒤에 두고 있었다. 난이도
 * 모디파이어·턴 지시 등 **모든 추가 블록은 그 앞**에 들어가야 하며, 그래서 이 함수는 호출부가
 * `buildSystemPrompt(...) + 추가지시`로 이어 붙이는 대신 `opts`로 받는다 —
 * `openingLine.ts`가 실제로 그 방식으로 가드레일 뒤에 지시를 붙이던 기존 위반(§15.6 G2)을
 * 이번 태스크에서 함께 제거했다.
 *
 * 확정 순서: persona → weakenedTactics → 대화 방식 → 진행 강제(문자 카탈로그가 있으면 "화면에 없는
 * 것" 항목이 조건형으로 대체됨, T68) → 확인 안내 동기화(T83, 조건형) → 난이도 → 턴 지시 →
 * **가드레일**.
 */
export function buildSystemPrompt(
  prompt: ScenarioPromptDoc,
  opts: BuildSystemPromptOptions = {},
): string {
  const tactics = prompt.weakenedTactics.map((tactic, i) => `${i + 1}. ${tactic}`).join("\n");
  const difficultyBlock = opts.difficultyLevel ? DIFFICULTY_MODIFIERS[opts.difficultyLevel] : null;
  return [
    prompt.personaPrompt,
    "",
    "[사용 가능한 수법(weakenedTactics) — 이 목록 밖의 수법, 특히 실제 운영 가능한 사기 수법을 스스로 만들지 않는다]",
    tactics,
    "",
    CONVERSATION_STYLE,
    "",
    // T68 — 문자 카탈로그가 있으면 "화면에 없는 것" 항목만 조건형으로 대체된다(§15.5 확정 순서 4번,
    // 블록 위치 자체는 이동하지 않는다).
    buildScenarioProgression(opts.inCallSmsEnabled === true),
    "",
    // 아래 세 블록은 "있을 때만" 삽입된다 — intermediate(=블록 없음)·확인 무력화 미적용·턴 지시
    // 없음인 경우 배열이 도입 전과 완전히 동일해져 조립 결과 문자열도 한 글자도 달라지지 않는다
    // (회귀 0 보장).
    ...(opts.verifyInterceptEnabled === true ? [VERIFY_INTERCEPT_RULE, ""] : []),
    ...(difficultyBlock ? [difficultyBlock, ""] : []),
    ...(opts.turnInstruction ? [opts.turnInstruction, ""] : []),
    prompt.guardrailPreamble,
  ].join("\n");
}

const USER_INPUT_OPEN = "[훈련참가자입력:데이터시작]";
const USER_INPUT_CLOSE = "[훈련참가자입력:데이터끝]";

// 구분자 리터럴을 여는/닫는 대괄호 "[...]" 형태로 흉내 낼 수 있는 사용자 입력을 무력화한다(T11,
// T7 reviewer Minor 지적: "사용자가 구분자 문자열을 그대로 흉내내면 문자열 레벨 2차 방어가
// 흐려질 수 있다"). 사용자 텍스트 안에 `[훈련참가자입력:...]` 형태가 그대로 들어오면 반각 대괄호를
// 전각 대괄호(［］)로 치환해, 실제 wrapUserInputAsData가 앞뒤에 삽입하는 진짜 구분자와 문자열이
// 절대 같아질 수 없게 만든다. 세션별 nonce를 구분자에 섞는 방법도 검토했으나, 구분자를 매 호출마다
// 재계산해야 하고 toLlmHistory로 과거 턴을 재구성할 때도 같은 nonce를 알아야 해 호출부(index.ts/
// toLlmHistory) 시그니처까지 건드려야 했다 — 이 이스케이프 방식은 이 함수 내부만 바꿔서 끝나
// 과설계를 피한다(구조적 방어인 role 분리가 이미 1차 방어라 이 정도로 충분, ADR-0004).
// T29 reviewer Major #4 — 사용자 입력 안에 `[[LINK:...]]`(스미싱 링크 마커, linkMarker.ts) 형태의
// 문자열이 그대로 들어와도, 실 LLM이 사용자 텍스트를 대사에 그대로 인용/반복하는 경우
// extractLinkMarker(어시스턴트 출력만 스캔하는 함수 자체는 안전하지만, LLM이 사용자 문구를
// 반향하면 그 반향된 텍스트가 어시스턴트 출력에 섞여 들어온다)가 이를 진짜 마커로 오인할 여지를
// 원천 차단한다. `[[SIGNAL:...]]`도 정규식에 이미 함께 포함돼(T29가 선제적으로 넣어 둠) 같은 보호를
// 받는다 — T30(에스컬레이션 구현)이 실제로 escalationSignal.ts의 감지 로직을 추가한 뒤 이 정규식이
// `[[SIGNAL:ESCALATE_VOICE]]` 흉내도 무력화함을 확인했다(별도 수정 불필요, 코드가 이미 앞서 있었음).
function escapeSentinelLookalikes(text: string): string {
  return text.replace(/\[\[(LINK|SIGNAL):/g, "［［$1：");
}

function escapeDelimiterLookalikes(text: string): string {
  return escapeSentinelLookalikes(text).replace(/\[(훈련참가자입력:[^\]]*)\]/g, "［$1］");
}

/**
 * 사용자 입력을 구분자로 감싼다(AC-013/AC-024 "사용자입력/시스템프롬프트 분리" 구조의 두 번째
 * 방어층 — 첫 번째 방어층은 role:"user" 분리 자체). LLM에게 "이 안의 내용은 지시가 아니라 훈련
 * 참가자가 보낸 데이터"임을 문자열 레벨에서도 명확히 표시한다.
 */
export function wrapUserInputAsData(text: string): string {
  const safeText = escapeDelimiterLookalikes(text);
  return `${USER_INPUT_OPEN}\n${safeText}\n${USER_INPUT_CLOSE}`;
}

/**
 * Firestore에 저장된 대화 이력(마스킹된 텍스트, 시간순)을 LLM 어댑터 입력 형식으로 변환한다.
 * 사용자 턴은 wrapUserInputAsData로 감싸 매 턴 반복적으로 데이터임을 표시한다.
 */
export function toLlmHistory(
  storedMessages: { role: "user" | "scammer"; textMasked: string }[],
): LlmMessage[] {
  return storedMessages.map((m) =>
    m.role === "user"
      ? { role: "user" as const, content: wrapUserInputAsData(m.textMasked) }
      : { role: "assistant" as const, content: m.textMasked },
  );
}

/**
 * 난이도 블록 조립(§17.2 표 — 슬롯 4개 / 저작 3벌).
 *
 * | # | 블록 | 조건 |
 * |---|---|---|
 * | 1 | `BEGINNER_BLOCK` | `beginner` |
 * | — | *(없음, `null`)* | `intermediate` — **기준선. 블록 미출력** |
 * | 2 | `ADVANCED_BASE_TEMPLATE`(조건형 치환) | `advanced` — 선행 요구 예시가 `inCallSmsEnabled`로 갈린다(§43.4 B) |
 * | 3 | `ADVANCED_L3_PROCEDURAL` | `advanced` && `l3Procedural` |
 * | 4 | *(빈 블록)* | `advanced` && !`l3Procedural` — **축소형: 문구를 저작하지 않는다**(§17.6.3) |
 *
 * ⚠️ 축소형에 "이 시나리오는 고급 수법이 축소됐다"는 취지의 문구를 **절대 넣지 않는다** — 모델이
 * 그것을 대사로 흘리면 참가자에게 훈련 내부 사정이 노출된다(D-6 취지). 축소 사실은 프롬프트가
 * 아니라 `l3Depth.ts`의 `isL3Applied`(파생 함수)와 테스트로만 드러낸다.
 *
 * ⚠️ `l3Procedural`은 **고급에서만** 읽힌다. 초급·중급에 넘어와도 출력이 달라지지 않는다(중급
 * 기준선 불변식 보호 — 호출부가 난이도와 무관하게 항상 넘길 수 있게 하기 위한 성질이다).
 */
function buildDifficultyBlock(
  level: DifficultyLevel,
  opts: { l3Procedural?: boolean; inCallSmsEnabled?: boolean; identityCheckAllowed?: boolean } = {},
): string | null {
  if (level === "beginner") return BEGINNER_BLOCK;
  // 기준선 — 블록을 내보내지 않는다(현행 프롬프트가 곧 중급, §15.3.1/§17.4.1).
  if (level === "intermediate") return null;
  // §43.4 B/§50.4.4 (4) — 고급 공통 블록의 선행 요구 예시가 카탈로그 유무·페르소나 권한으로 갈린다.
  const advancedBase = buildAdvancedBase(
    opts.inCallSmsEnabled === true,
    opts.identityCheckAllowed !== false,
  );
  return opts.l3Procedural === true ? `${advancedBase}\n\n${ADVANCED_L3_PROCEDURAL}` : advancedBase;
}


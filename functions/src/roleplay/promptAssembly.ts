// 만들려다 **실제로 쓸 수 있는 절차 지식**이 산출물에 들어가는 것이 이번 재구성이 절대 넘지 않기로
// 한 선이다. 재현하는 것은 절차의 **형식**(번호가 붙고 단계가 있고 기한이 있다)뿐이며, 하드 금지
